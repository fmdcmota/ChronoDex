/**
 * Render `data/ATTRIBUTION.md`: licence and author of every third-party file used or shown.
 *
 * Owner: Agent 5 (Archivist). Implements AGENT5.md section 5.6, task A5-11.
 * CC BY and CC BY-SA require attribution wherever a file is shown, and the image models are given
 * these files, so the Sources drawer (Agent 4) and the credits read this table. It is generated
 * from the JSON by ./build.ts and compared by ./validate.ts, so it cannot fall behind the data.
 */
import type { EraFile, LandmarkFile } from './schema';

/** One row of the attribution table. */
export interface AttributionRow {
  /** The file page that states the licence. */
  pageUrl: string;
  title: string;
  author: string;
  licence: string;
  /** Where the licence text can be read, or an empty string for public-domain files. */
  licenceUrl: string;
  /** Every use of the file, for example "reference photo for queens-tower". */
  uses: string[];
}

/**
 * The URL of a Creative Commons licence deed, from the licence as the source states it.
 *
 * @param licence - For example "CC BY-SA 4.0" or "Public domain".
 * @returns The deed URL, or an empty string when the licence is not a Creative Commons one.
 */
export function licenceUrlOf(licence: string): string {
  const text = licence.trim().toLowerCase();
  if (/^cc0|^cc zero/.test(text)) return 'https://creativecommons.org/publicdomain/zero/1.0/';
  const match = /^cc[ -]by([ -]sa)?[ -](\d(?:\.\d)?)(?: ([a-z-]+))?$/.exec(text);
  if (!match) return '';
  const kind = match[1] ? 'by-sa' : 'by';
  const version = match[2].includes('.') ? match[2] : `${match[2]}.0`;
  // National ports ("CC BY-SA 2.0 uk") have their own deed path.
  const port = match[3] ? `${match[3]}/` : '';
  return `https://creativecommons.org/licenses/${kind}/${version}/${port}`;
}

/**
 * Collect one row per third-party file across all landmarks and eras, merging repeated uses.
 *
 * @param landmarks - Every landmark file.
 * @param eras - Every era dossier.
 * @returns Rows sorted by file page URL.
 */
export function attributionRows(landmarks: readonly LandmarkFile[], eras: readonly EraFile[]): AttributionRow[] {
  const rows = new Map<string, AttributionRow>();
  const add = (row: Omit<AttributionRow, 'uses' | 'licenceUrl'>, use: string) => {
    const existing = rows.get(row.pageUrl);
    if (existing) existing.uses.push(use);
    else rows.set(row.pageUrl, { ...row, licenceUrl: licenceUrlOf(row.licence), uses: [use] });
  };
  for (const landmark of landmarks) {
    const photo = landmark.referencePhoto;
    if (photo.status !== 'commons_stand_in' || !photo.pageUrl) continue;
    add(
      { pageUrl: photo.pageUrl, title: `Present-day photo of ${landmark.name}`, author: photo.author ?? 'Unknown', licence: photo.licence ?? 'Unknown' },
      `reference photo for ${landmark.id} (fitted to 16:9, shown in app, model input)`,
    );
  }
  for (const era of eras) {
    if (era.status === 'rejected') continue;
    for (const image of era.referenceImages) {
      add(
        { pageUrl: image.pageUrl, title: image.title, author: image.author, licence: image.licence },
        image.match === 'context' ? `period context for ${era.eraId} (cited, not model input)` : `model input for ${era.eraId}`,
      );
    }
  }
  return [...rows.values()].sort((a, b) => a.pageUrl.localeCompare(b.pageUrl));
}

/**
 * Escape text for a Markdown table cell.
 *
 * @param text - Any text.
 * @returns The text on one line with pipes escaped.
 */
function cell(text: string): string {
  return text.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
}

/**
 * Render the attribution file.
 *
 * @param landmarks - Every landmark file.
 * @param eras - Every era dossier.
 * @returns Markdown text ending with a newline.
 */
export function renderAttribution(landmarks: readonly LandmarkFile[], eras: readonly EraFile[]): string {
  const rows = attributionRows(landmarks, eras);
  const lines = [
    '# Attribution',
    '',
    'Every third-party file Chronodex uses as model input or shows in the app, with its author and',
    'licence as stated on its file page. Generated by `npx tsx scripts/data/build.ts` from the JSON in',
    '`data/landmarks/` and `data/eras/`: do not edit by hand. Team reference photos (H1) are our own',
    'and are not listed. Images generated by the pipeline are AI reconstructions, labelled as such in',
    'the app.',
    '',
    '| File | Author | Licence | Used as |',
    '|---|---|---|---|',
    ...rows.map((row) => {
      const licence = row.licenceUrl ? `[${cell(row.licence)}](${row.licenceUrl})` : cell(row.licence);
      return `| [${cell(row.title)}](${row.pageUrl}) | ${cell(row.author)} | ${licence} | ${cell(row.uses.join('; '))} |`;
    }),
  ];
  if (rows.length === 0) lines.push('| (none yet) | | | |');
  return `${lines.join('\n')}\n`;
}
